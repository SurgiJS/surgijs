// Derives the Custom Elements Manifest and the React and Vue typings from the defineComponent
// calls in src/. Run `pnpm generate` after changing a component; the test suite fails on drift.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const PACKAGE = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const SCHEMA_VERSION = '1.0.0';
const REFLECTED = new Set(['String', 'Number', 'Boolean']);
const GENERATED = '// Generated by packages/ui/scripts/manifest.mjs from the defineComponent calls in src/. Do not edit by hand.';

const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const pascal = (tag) => tag.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const toText = (parts) => ts.displayPartsToString(parts).trim().replace(/\s*\n\s*/g, ' ');
const posix = (p) => p.split(sep).join('/');

function publishedModule(dirName) {
  const target = PACKAGE.exports[`./${dirName}`]?.import;
  if (!target) throw new Error(`package.json has no "./${dirName}" export with an import target`);
  return posix(target.replace(/^\.\//, ''));
}

function componentEntries() {
  return readdirSync(SRC, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => join(SRC, d.name, 'index.ts'))
    .filter((file) => existsSync(file))
    .sort();
}

function createProgram(rootNames) {
  const { config, error } = ts.readConfigFile(join(ROOT, 'tsconfig.json'), ts.sys.readFile);
  if (error) throw new Error(ts.flattenDiagnosticMessageText(error.messageText, '\n'));
  const parsed = ts.parseJsonConfigFileContent(config, ts.sys, ROOT);
  return ts.createProgram({ rootNames, options: { ...parsed.options, noEmit: true } });
}

function findDefineCalls(node, calls = []) {
  if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === 'defineComponent') {
    calls.push(node);
  }
  ts.forEachChild(node, (child) => {
    findDefineCalls(child, calls);
  });
  return calls;
}

function initializerOf(checker, identifier) {
  let symbol = checker.getSymbolAtLocation(identifier);
  if (symbol && symbol.flags & ts.SymbolFlags.Alias) symbol = checker.getAliasedSymbol(symbol);
  const initializer = symbol?.valueDeclaration?.initializer;
  if (!initializer) throw new Error(`\`${identifier.text}\` must be initialized with a value in its module`);
  return initializer;
}

function unwrap(node) {
  while (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node)) {
    node = node.expression;
  }
  return node;
}

function parseSchema(checker, node) {
  if (!node) return [];
  const init = unwrap(ts.isIdentifier(node) ? initializerOf(checker, node) : node);
  if (!ts.isObjectLiteralExpression(init)) throw new Error('defineComponent schema must be an object literal');
  return init.properties.map((prop) => {
    if (!ts.isPropertyAssignment(prop) || !ts.isIdentifier(prop.name) || !ts.isIdentifier(prop.initializer)) {
      throw new Error(`Unsupported schema entry: ${prop.getText()}`);
    }
    return { name: prop.name.text, ctor: prop.initializer.text };
  });
}

function parseRender(checker, node) {
  if (!ts.isIdentifier(node)) throw new Error('defineComponent render must be a named function');
  const fn = unwrap(initializerOf(checker, node));
  const slots = [];
  const parts = [];
  const visit = (n) => {
    if ((ts.isJsxOpeningElement(n) || ts.isJsxSelfClosingElement(n)) && ts.isIdentifier(n.tagName) && n.tagName.text === 'slot') {
      const name = n.attributes.properties.find((a) => ts.isJsxAttribute(a) && a.name.text === 'name');
      slots.push(name && ts.isStringLiteral(name.initializer) ? name.initializer.text : '');
    }
    if (ts.isJsxOpeningElement(n) || ts.isJsxSelfClosingElement(n)) {
      for (const attr of n.attributes.properties) {
        if (ts.isJsxAttribute(attr) && attr.name.text === 'part' && attr.initializer && ts.isStringLiteral(attr.initializer)) {
          parts.push(...attr.initializer.text.split(/\s+/).filter(Boolean));
        }
      }
    }
    ts.forEachChild(n, visit);
  };
  visit(fn);
  return { slots: [...new Set(slots)], parts: [...new Set(parts)] };
}

function typeText(checker, symbol) {
  const type = checker.getNonNullableType(checker.getTypeOfSymbol(symbol));
  if (checker.typeToString(type) === 'boolean') return 'boolean';
  if (type.isUnion()) return type.types.map((t) => checker.typeToString(t)).join(' | ');
  return checker.typeToString(type);
}

function customProperties(entry, tag) {
  const names = new Set();
  const pattern = new RegExp(`var\\(--${tag}-([a-z0-9-]+)`, 'g');
  for (const file of readdirSync(dirname(entry))) {
    if (!/\.tsx?$/.test(file)) continue;
    for (const match of readFileSync(join(dirname(entry), file), 'utf8').matchAll(pattern)) {
      names.add(`--${tag}-${match[1]}`);
    }
  }
  return [...names].sort().map((name) => ({ name }));
}

function describeComponent(checker, entry, call) {
  const tagNode = call.arguments[0];
  if (!tagNode || !ts.isStringLiteral(tagNode)) throw new Error(`${entry}: defineComponent needs a literal tag name`);
  const tag = tagNode.text;
  const declaration = call.parent;
  if (!ts.isVariableDeclaration(declaration) || !ts.isIdentifier(declaration.name)) {
    throw new Error(`${entry}: defineComponent(${tag}) must initialize an exported const`);
  }
  const className = declaration.name.text;
  const classSymbol = checker.getSymbolAtLocation(declaration.name);

  const propsNode = call.typeArguments?.[0];
  if (!propsNode) throw new Error(`${entry}: defineComponent(${tag}) needs its props type as a type argument`);
  const propsType = checker.getTypeFromTypeNode(propsNode);
  const propsSymbol = propsType.getSymbol();
  const propsDeclaration = propsSymbol?.declarations?.[0];
  if (!propsSymbol || !propsDeclaration) throw new Error(`${entry}: cannot resolve the props type of ${tag}`);
  const propsModule = posix(relative(ROOT, propsDeclaration.getSourceFile().fileName));

  const members = [];
  const attributes = [];
  for (const { name, ctor } of parseSchema(checker, call.arguments[2])) {
    const prop = propsType.getProperty(name);
    if (!prop) throw new Error(`${entry}: ${tag} declares "${name}" in its schema but not in ${propsSymbol.name}`);
    const doc = prop.getDocumentationComment(checker);
    const defaultTag = prop.getJsDocTags(checker).find((t) => t.name === 'default');
    const attribute = kebab(name);
    const reflects = REFLECTED.has(ctor);
    const common = {
      type: { text: typeText(checker, prop) },
      description: toText(doc) || undefined,
      default: defaultTag?.text ? toText(defaultTag.text) : undefined,
    };
    members.push({ kind: 'field', name, ...common, attribute, reflects: reflects || undefined });
    attributes.push({ name: attribute, fieldName: name, ...common });
  }

  const { slots, parts } = parseRender(checker, call.arguments[1]);
  const classDoc = classSymbol ? toText(classSymbol.getDocumentationComment(checker)) : '';
  const modulePath = publishedModule(basename(dirname(entry)));

  return {
    module: {
      kind: 'javascript-module',
      path: modulePath,
      declarations: [
        {
          kind: 'class',
          name: className,
          customElement: true,
          tagName: tag,
          description: classDoc || undefined,
          members,
          attributes,
          slots: slots.map((name) => ({ name })),
          cssParts: parts.map((name) => ({ name })),
          cssProperties: customProperties(entry, tag),
        },
      ],
      exports: [
        {
          kind: 'custom-element-definition',
          name: tag,
          declaration: { name: className, module: modulePath },
        },
      ],
    },
    tag,
    className,
    propsName: propsSymbol.name,
    propsModule,
  };
}

export function buildManifest() {
  const entries = componentEntries();
  const program = createProgram(entries);
  const checker = program.getTypeChecker();
  const components = entries.flatMap((entry) => {
    const sourceFile = program.getSourceFile(entry);
    if (!sourceFile) throw new Error(`Missing source file ${entry}`);
    return findDefineCalls(sourceFile).map((call) => describeComponent(checker, entry, call));
  });
  return {
    schemaVersion: SCHEMA_VERSION,
    modules: components.map((c) => c.module),
    components,
  };
}

function toManifest({ components, ...manifest }) {
  return manifest;
}

function propsImports(components) {
  const byModule = new Map();
  for (const c of components) {
    const specifier = './' + c.propsModule.replace(/^src\//, '').replace(/\.tsx?$/, '');
    if (!byModule.has(specifier)) byModule.set(specifier, new Set());
    byModule.get(specifier).add(c.propsName);
  }
  return [...byModule]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([specifier, names]) => `import type { ${[...names].sort().join(', ')} } from '${specifier}';`);
}

export function renderReact(manifest) {
  const body = manifest.components
    .map((c) => `      '${c.tag}': React.DetailedHTMLProps<React.HTMLAttributes<HTMLElement>, HTMLElement> & ${c.propsName};`)
    .join('\n');
  return [
    GENERATED,
    `import type * as React from 'react';`,
    ...propsImports(manifest.components),
    '',
    `declare module 'react' {`,
    `  namespace JSX {`,
    `    interface IntrinsicElements {`,
    body,
    `    }`,
    `  }`,
    `}`,
    '',
  ].join('\n');
}

export function renderVue(manifest) {
  const body = manifest.components.map((c) => `    ${pascal(c.tag)}: DefineComponent<${c.propsName}>;`).join('\n');
  return [
    GENERATED,
    `import type { DefineComponent } from 'vue';`,
    ...propsImports(manifest.components),
    '',
    `declare module 'vue' {`,
    `  export interface GlobalComponents {`,
    body,
    `  }`,
    `}`,
    '',
  ].join('\n');
}

export function generatedFiles(manifest = buildManifest()) {
  return {
    'custom-elements.json': JSON.stringify(toManifest(manifest), null, 2) + '\n',
    'src/react.ts': renderReact(manifest),
    'src/vue.ts': renderVue(manifest),
  };
}

export function generate() {
  for (const [file, contents] of Object.entries(generatedFiles())) {
    writeFileSync(join(ROOT, file), contents);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generate();
